const CodeHeader = "// Code generated by genlua."

func CheckHeader(fname, s string) error {
	if !strings.HasPrefix(s, CodeHeader) {
		return errors.New(fmt.Sprintf("`%s` is not generated by genlua.", fname))
	}
	return nil
}

func GenLua(filename string, in []byte, formatCode bool) ([]byte, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, filename, in, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	code := &Code{}
	code.CodeHeader = CodeHeader
	code.FileName = filename
	code.PkgName = f.Name.Name
	code.ModuleName = strings.ToLower(code.PkgName)
	structName := ""
	var fields []CodeField

	for name, obj := range f.Scope.Objects {
		spec, ok := obj.Decl.(*ast.TypeSpec)
		if ok {
			stype, ok := spec.Type.(*ast.StructType)
			if ok {
				structName = name
				for _, x := range stype.Fields.List {
					if x.Tag != nil && len(x.Names) > 0 && strings.HasPrefix(x.Tag.Value, "`lua") {
						//TODO:switch
						fname := x.Names[0].Name
						cname := fname
						name1 := ParseTag(x.Tag.Value)
						if name1 != "" {
							cname = name1
						}
						vname := fmt.Sprintf("v0.%s", fname)
						ftype := ""
						switch tt := x.Type.(type) {
						case *ast.Ident:
							ftype = tt.Name
						default:
							fmt.Printf("%T,%+v\n", x.Type, x.Type)
						}
						if ftype != "" {
							fcode := GenPushCode(ftype, vname, 0, false)
							if fcode != "" {
								fields = append(fields, CodeField{
									StructName: structName,
									FieldName:  fname,
									Name:       cname,
									Code:       fcode,
								})
							}
						}
					}
				}
				break
			}
		}
	}

	if len(fields) > 0 {
		code.Fields = fields
	}
	code.StructName = structName

	var funcNew *CodeFunc
	var funcs []CodeFunc
	for _, d := range f.Decls {
		fd, ok := d.(*ast.FuncDecl)
		makeUdata := false
		udataToBytes := false
		if ok {
			funcName := fd.Name.Name
			name := funcName
			if fd.Doc != nil {
				funcName1, makeUdata1, udataToBytes1 := ParseDoc(fd.Doc)
				if funcName1 != "" {
					name = funcName1
				}
				if makeUdata1 {
					makeUdata = makeUdata1
				}
				if udataToBytes1 {
					udataToBytes = udataToBytes1
				}
			}
			paramIdx := 1
			if fd.Recv != nil {
				paramIdx = 2
			}
			paramList, resultList, params,
				results, structID := ParseFunc(fd, paramIdx, makeUdata, udataToBytes)
			if fd.Recv != nil {
				rtype := fd.Recv.List[0].Type
				if rt1, ok := rtype.(*ast.StarExpr); ok {
					tname := rt1.X.(*ast.Ident).Name // Type Name
					if tname == structName {         // Recv Must be Current Type
						cf := CodeFunc{
							Name:       name,
							FuncName:   funcName,
							StructID:   structID,
							StructName: structName,
							ParamList:  paramList,
							ResultList: resultList,
							Params:     params,
							Results:    results,
						}
						funcs = append(funcs, cf)
					}
				}
			} else {
				if funcName == structName+"New" {
					funcNew = &CodeFunc{
						StructName: structName,
						ParamList:  paramList,
						ResultList: resultList,
						Params:     params,
						Results:    results,
					}
					code.FuncNew = funcNew
				}
			}
		}
	}
	if len(funcs) > 0 {
		code.Funcs = funcs
	}
	return codeExec(codeTemplate, code, formatCode)
}

func codeExec(t *template.Template, data interface{}, formatCode bool) ([]byte, error) {
	buf := new(bytes.Buffer)
	if err := t.Execute(buf, data); err != nil {
		return nil, err
	}
	if formatCode {
		return format.Source(buf.Bytes())
	}
	return buf.Bytes(), nil
}
